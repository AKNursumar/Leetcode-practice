class Solution:
    def countCommas(self, n: int) -> int:
        if n<=999:
            return 0
        if n>999 and n<=999999:
            return n-999
        elif n>999999 and n<=999999999:
            return (n-999999)*2+999999-999
        elif n>999999999 and n<=999999999999:
            return (n-999999999)*3+(n-(n-999999999)-999999)*2+999999-999
        elif n>999999999999 and n<=999999999999999:
            return (n-999999999999)*4+(n-(n-999999999999)-999999999)*3+(n-(n-999999999999)-(n-(n-999999999999)-999999999)-999999)*2+999999-999
        else:
            return (n-999999999999)*4+(n-(n-999999999999)-999999999)*3+(n-(n-999999999999)-(n-(n-999999999999)-999999999)-999999)*2+999999-999+1
        